export type Place = { kind: "japan"; ll: LL; short: string } | { kind: "abroad"; short: string };

// 住んだ場所の名前 → 地図の上の位置。「海外の国・街」の形は、海外として扱う。
export function resolvePlace(raw: string): Place {
  const name = raw.replace(/(\(.*\))$/, "").trim();
  const short = name.includes("・") ? name.split("・").pop()!.replace(/(の郊外|の外れ)$/, "") : name;
  if (CITY[name]) return { kind: "japan", ll: CITY[name], short };
  if (PREF[name]) return { kind: "japan", ll: PREF[name], short: name };
  if (name.startsWith("東京")) return { kind: "japan", ll: PREF["東京都"], short };
  for (const [pref, ll] of Object.entries(PREF)) {
    if (name.startsWith(pref)) return { kind: "japan", ll, short };
  }
  return { kind: "abroad", short: name };
}

