export type EpitaphInput = { seed: number; age: number; cause: string; joy: number; bonds: number; money: number };

// 年齢・原因・気持ちに合う、ひとことを、1つ選ぶ。同じ人生なら、いつも同じものが出る。
export function pickEpitaph(i: EpitaphInput): string {
  const pool: string[] = [...E.any];
  const agePool = i.age < 30 ? E.young : i.age < 60 ? E.mid : i.age < 85 ? E.late : E.long;
  // 年齢に合うものを、多めに入れる(2倍)。
  pool.push(...agePool, ...agePool);
  if (/事故|災害|遭難|事件|突然/.test(i.cause)) pool.push(...E.sudden, ...E.sudden);
  if (/がん|病|心臓|脳|肺炎|糖尿|難病|闘病/.test(i.cause)) pool.push(...E.illness, ...E.illness);
  if (i.joy >= 70) pool.push(...E.happy, ...E.happy);
  if (i.bonds < 30) pool.push(...E.lonely, ...E.lonely);
  if (i.money < 25 || i.joy < 30) pool.push(...E.hard);
  const rng = createRng((i.seed ^ Math.imul(i.age + 7, 2654435761)) >>> 0);
  return pool[Math.floor(rng() * pool.length)];
}

export const EPITAPH_COUNT = Object.values(E).reduce((n, a) => n + a.length, 0);
