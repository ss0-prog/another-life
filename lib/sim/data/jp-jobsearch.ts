const norm = (s: string) => s.normalize("NFKC").toLowerCase();
// カタカナ → ひらがな
export const toHira = (s: string) => norm(s).replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60));

// 五十音の行(あ・か・さ…)。濁点・半濁点・小さい文字は、もとの文字として数える。
export const GYO: { key: string; label: string; chars: string }[] = [
  { key: "a", label: "あ", chars: "あいうえおぁぃぅぇぉ" },
  { key: "k", label: "か", chars: "かきくけこ" },
  { key: "s", label: "さ", chars: "さしすせそ" },
  { key: "t", label: "た", chars: "たちつてとっ" },
  { key: "n", label: "な", chars: "なにぬねの" },
  { key: "h", label: "は", chars: "はひふへほ" },
  { key: "m", label: "ま", chars: "まみむめも" },
  { key: "y", label: "や", chars: "やゆよゃゅょ" },
  { key: "r", label: "ら", chars: "らりるれろ" },
  { key: "w", label: "わ", chars: "わをんゎ" },
];
const strip = (c: string) => c.normalize("NFD").replace(/[゙゚]/g, "");
export const gyoOf = (reading: string): string | null => {
  const first = strip(toHira(reading).charAt(0));
  return GYO.find((g) => g.chars.includes(first))?.key ?? null;
};

export type JobHit = { value: string; score: number; why?: string };

// 検索窓に書かれた言葉から、職種を探す。
// 1) 職種名・読み・言いかえに、書かれた言葉が含まれる  2) 「動物が好き」のような、やりたいことの言い方から連想する
export function searchJobs(
  text: string,
  items: { value: string; label: string }[],
  kw: Record<string, RegExp | undefined> = {},
  limit = 8,
): JobHit[] {
  const q = norm(text).trim();
  if (!q) return [];
  const qh = toHira(q).replace(/\s+/g, "");
  const present = new Set(items.map((i) => i.value));
  const hits = new Map<string, JobHit>();
  const add = (value: string, score: number, why?: string) => {
    if (!present.has(value)) return;
    const cur = hits.get(value);
    if (!cur) hits.set(value, { value, score, why });
    else {
      cur.score += score;
      if (!cur.why && why) cur.why = why;
    }
  };

  for (const it of items) {
    const label = norm(it.label);
    const reading = toHira(READING[it.value] ?? "");
    const alias = toHira(ALIAS[it.value] ?? "");
    // 短すぎる1文字は、あいまいなので、点を低くする
    const w = qh.length >= 2 ? 1 : 0.4;
    if (label.includes(q)) add(it.value, 12 * w, "名前");
    else if (toHira(label).includes(qh)) add(it.value, 10 * w, "名前");
    if (reading) {
      const words = reading.split(/\s+/);
      if (words.some((x) => x.startsWith(qh))) add(it.value, 11 * w, "読み");
      else if (reading.includes(qh)) add(it.value, 6 * w, "読み");
    }
    if (alias) {
      const words = alias.split(/\s+/);
      if (words.some((x) => x === qh)) add(it.value, 13, "言いかえ");
      else if (words.some((x) => qh.length >= 2 && (x.includes(qh) || (x.length >= 3 && qh.includes(x))))) add(it.value, 8, "言いかえ");
    }
    const re = kw[it.value];
    if (re && re.test(q)) add(it.value, 9, "名前");
  }

  // やりたいこと・好きなこと(文章)からの連想
  for (const c of CONCEPTS) {
    if (c.re.test(q)) c.ids.forEach((id, i) => add(id, 7 - i * 0.6, `「${c.why}」から`));
  }

  // 文章に、職種名の一部(2文字以上)がそのまま出てくるとき
  if (q.length >= 4) {
    for (const it of items) {
      const title = norm(it.label).replace(/[(（].*$/, "");
      for (const part of title.split(/[・、,]/)) {
        if (part.length >= 2 && q.includes(part)) add(it.value, 9, "名前");
      }
    }
  }

  return [...hits.values()].sort((a, b) => b.score - a.score).slice(0, limit);
}
