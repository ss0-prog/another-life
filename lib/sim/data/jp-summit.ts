// 頂点にのぼりつめる年ごとの確率(運は、実力・つながり・健康・幸福度で、少しだけ傾く)。
export function summitChance(p: Person, s: Summit): number {
  const lift = (p.stats.learn / 60) * (0.6 + p.stats.bonds / 125) * (0.7 + p.stats.health / 200) * (0.8 + p.stats.joy / 250);
  return s.base * 0.4 * (0.6 + p.extra.career / 100) * Math.max(0.3, Math.min(2.5, lift)) * (0.6 + p.intel / 150);
}
