// 家族・ペット(名前つき)。
function familyLines(p: Person): string[] {
  const out: string[] = [];
  const kid = p.kidList[0];
  if (kid && p.age - kid.bornAge < 18 && p.age - kid.bornAge >= 0) out.push(`${kid.name || "子ども"}が、学校や園から帰ってきて、玄関が一気ににぎやかになる。`, `${kid.name || "子ども"}の寝顔を見ながら、一日を終える。`);
  if (kid && p.age - kid.bornAge >= 18) out.push(`${kid.name || "子ども"}からの短いメッセージに、思わず頬がゆるんだ。`);
  const pet = p.pets.find((x) => !x.died);
  if (pet) out.push(`${pet.name ? pet.kind + "の" + pet.name : pet.kind}が、足もとで丸くなっている。`, `${pet.name ? pet.kind + "の" + pet.name : pet.kind}の寝息を聞きながら、静かに時が流れていく。`);
  const deadPet = p.pets.find((x) => x.died);
  if (deadPet) out.push(`${deadPet.name}がいない部屋が、まだ少し広く感じる。`);
  if (p.married) out.push("台所から、パートナーの立てる音がしている。", "隣に誰かがいる安心感を、ふと噛みしめた。");
  else if (!p.withParents && p.age >= 25) out.push("ひとりの部屋の静けさが、心地よくもあり、少し寂しくもある。");
  if (p.withParents) out.push("階下から、家族の話し声が聞こえてくる。");
  return out;
}

// 6つの引き出しから、年ごとに違うものを2つ選ぶ。
export function vignette(p: Person, seed: number): string {
  const rng = createRng((seed ^ Math.imul(p.age + 7, 2246822519)) >>> 0);
  const season = seasonOf(p.age, seed);
  const weather = weatherAt(seed, p.age);
  const pref = prefectureOf(p.city) || p.birthPlace;
  const place = PLACES[pref];
  const seasonKey = season === "冬" ? "winter" : season === "夏" ? "summer" : season === "春" ? "spring" : "autumn";
  // 海外で暮らしているときは、その国の暮らしの描写を使う。
  const country = p.abroad ? COUNTRIES.find((c) => c.name === p.abroad!.country) : undefined;
  const placeLines = country ? country.lines : [...(place?.[seasonKey] ?? []), ...(place?.any ?? []), ...(place ? [] : REGION_FALLBACK[p.region])];
  // 雪の降る空模様のときは、雪国の描写を優先する。
  const snowy = !country && weather === "snow" && (pref === "北海道" || place?.winter);
  const drawers: { name: string; lines: string[]; w: number }[] = [
    { name: "place", lines: snowy && place?.winter ? place.winter : placeLines, w: 3 },
    { name: "weather", lines: WEATHER_LINES[weather], w: 2.2 },
    { name: "season", lines: SEASON_LINES[season], w: 1 },
    { name: "feel", lines: feelings(p), w: 3.2 },
    { name: "work", lines: p.occ ? (WORK[p.occ] ?? []) : [], w: 1.6 },
    { name: "family", lines: familyLines(p), w: 2.4 },
    { name: "stage", lines: stageLines(p), w: 2 },
  ];
  // 重みつきで、中身のある引き出しから、重ならないように2つ選ぶ。
  const picked: string[] = [];
  const pool = drawers.filter((d) => d.lines.length > 0);
  for (let i = 0; i < 2 && pool.length; i++) {
    const total = pool.reduce((s, d) => s + d.w, 0);
    let r = rng() * total;
    let idx = pool.length - 1;
    for (let k = 0; k < pool.length; k++) {
      r -= pool[k].w;
      if (r < 0) {
        idx = k;
        break;
      }
    }
    picked.push(pick(rng, pool[idx].lines));
    pool.splice(idx, 1);
  }
  return `${season}。${picked.join("")}`;
}
